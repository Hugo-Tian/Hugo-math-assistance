import { test,expect } from '@playwright/test'
test.skip(!process.env.AI_MOCK_E2E,'Explicit Mock suite; requires isolated test backend, not a real model acceptance test.')

test('Mock assistant + REAL embedding: knowledge → source → wrong explanation → plan → save → practice → report',async({page,request})=>{
  const username=`ai_e2e_${Date.now()}`
  await request.post('/api/auth/register',{data:{username,password:'Password123!'}})
  await page.goto('/')
  await page.getByLabel('用户名',{exact:true}).fill(username)
  await page.getByLabel('密码',{exact:true}).fill('Password123!')
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await page.getByRole('link',{name:'知识树',exact:true}).click()
  await page.getByTestId('node-derivative_rules').click()
  await page.getByRole('link',{name:'向 AI 提问',exact:true}).click()
  await page.getByRole('button',{name:'发送问题',exact:true}).click()
  await expect(page.locator('.citation-cards button').first()).toBeVisible()
  await expect(page.locator('.assistant-answer')).toContainText('测试 Mock')
  await page.locator('.citation-cards button').first().click()
  await expect(page.getByRole('dialog',{name:'引用原文'})).toContainText('自编演示资料')
  await page.screenshot({path:'docs/screenshots/assistant-citation-mock.png',fullPage:true})
  await page.getByRole('button',{name:'关闭原文 ×'}).click()
  await page.getByRole('link',{name:'练习中心',exact:true}).click()
  await page.getByLabel('题量',{exact:true}).selectOption('1')
  await page.getByRole('button',{name:'开始练习',exact:true}).click()
  await page.getByTestId('option-0').click()
  await page.getByRole('button',{name:'提交答案',exact:true}).click()
  await page.getByRole('link',{name:'讲解这道题',exact:true}).click()
  await page.getByRole('button',{name:'发送问题',exact:true}).click()
  await expect(page.locator('.assistant-answer')).toContainText('测试 Mock')
  await page.getByLabel('你的问题',{exact:true}).fill('根据我最近的错题，帮我安排三天复习。')
  await page.getByLabel('回答方式').selectOption('agent')
  await page.getByRole('button',{name:'发送问题',exact:true}).click()
  await expect(page.locator('.study-plan')).toBeVisible()
  await expect(page.locator('.plan-day')).toHaveCount(3)
  await page.getByRole('button',{name:'保存计划',exact:true}).click()
  await expect(page.getByRole('button',{name:'计划已保存'})).toBeVisible()
  await page.screenshot({path:'docs/screenshots/assistant-plan-mock.png',fullPage:true})
  await page.getByRole('button',{name:'开始练习',exact:true}).first().click()
  await expect(page.getByRole('button',{name:'提交答案',exact:true})).toBeVisible()
  await page.getByTestId('option-0').click()
  await page.getByRole('button',{name:'提交答案',exact:true}).click()
  await expect(page.getByTestId('answer-feedback')).toBeVisible()
  await page.getByRole('link',{name:'学习报告',exact:true}).click()
  await expect(page.getByTestId('report-total')).toHaveText('2')
  await page.reload();await expect(page.getByTestId('report-total')).toHaveText('2')
})

test('model HTML output is inert, citations never navigate to arbitrary URLs',async({page,request})=>{
  // Exercise the exact UI renderer with a mocked HTTP response, independent of model intelligence.
  await page.route('**/api/assistant/conversations/render-fixture',route=>route.fulfill({json:{id:'render-fixture',title:'安全渲染测试',turns:[{id:'fixture',question:'测试',answer:'<img src=x onerror="window.__injected=1"><script>window.__injected=2</script> [恶意](javascript:alert(1))\n\n$f(x)=x^2$',status:'completed',provider_mode:'mock',citations:[]}]}}))
  await page.route('**/api/assistant/conversations',route=>route.request().method()==='GET'?route.fulfill({json:[{id:'render-fixture',title:'安全渲染测试'}]}):route.continue())
  await page.goto('/')
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await page.getByRole('link',{name:'学习助手',exact:true}).click()
  await expect(page.locator('.safe-markdown .katex')).toBeVisible()
  expect(await page.evaluate(()=>window.__injected)).toBeUndefined()
  await expect(page.locator('.safe-markdown img,.safe-markdown script,.safe-markdown a')).toHaveCount(0)
})
