import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
const bank=JSON.parse(readFileSync('data/demo_questions.json','utf8'))

test('login → recommendation → wrong answer → mastery → mistakes → recommendation → refresh', async ({ page, request }) => {
  const username=`e2e_${Date.now()}`
  await request.post('/api/auth/register',{data:{username,password:'Password123!'}})
  await page.goto('/')
  await page.getByLabel('用户名',{exact:true}).fill(username)
  await page.getByLabel('密码',{exact:true}).fill('Password123!')
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await expect(page.getByTestId('recommendation-name')).toHaveText('集合运算')
  await page.getByRole('button',{name:'开始自适应练习'}).click()
  await page.getByRole('button',{name:'开始练习',exact:true}).click()
  const q=bank[0]
  await page.getByTestId(`option-${(q.answer+1)%4}`).click()
  await page.getByRole('button',{name:'提交答案',exact:true}).click()
  await expect(page.getByTestId('answer-feedback')).toContainText('33%')
  await expect(page.getByTestId('answer-feedback')).toContainText('1 条有效样本')
  await page.screenshot({path:'docs/screenshots/answer-feedback.png',fullPage:true})
  await page.getByRole('link',{name:'学习报告',exact:true}).click()
  await expect(page.getByTestId('report-total')).toHaveText('1')
  await page.getByRole('link',{name:'错题本',exact:true}).click()
  await expect(page.getByTestId('mistake-row')).toHaveCount(1)
  await expect(page.getByTestId('mistake-row')).toContainText('累计错误 1 次')
  await page.getByRole('link',{name:'知识树',exact:true}).click()
  await expect(page.getByTestId('node-sets')).toContainText('33%')
  await page.getByTestId('node-derivative_rules').click()
  await expect(page.locator('.knowledge-detail h2')).toHaveText('导数计算')
  await page.getByTestId('node-extrema').click()
  await expect(page.locator('.knowledge-detail h2')).toHaveText('函数极值')
  await page.getByRole('link',{name:'学习首页',exact:true}).click()
  await expect(page.getByTestId('recommendation-name')).toHaveText('集合运算')
  await page.reload()
  await expect(page.getByTestId('recommendation-name')).toHaveText('集合运算')
  await page.getByRole('link',{name:'学习报告',exact:true}).click()
  await expect(page.getByTestId('report-total')).toHaveText('1')
  await page.screenshot({path:'docs/screenshots/report.png',fullPage:true})
})

test('two demo histories share goal but get different recommendations; responsive view', async ({ page }) => {
  for (const [username,expected,file] of [['demo_foundation','函数单调性','dashboard-foundation'],['demo_advanced','导数计算','dashboard-advanced']]) {
    await page.goto('/')
    await page.getByLabel('用户名',{exact:true}).fill(username)
    await page.getByLabel('密码',{exact:true}).fill('DemoMath2026!')
    await page.getByRole('button',{name:'登录',exact:true}).click()
    await expect(page.getByTestId('recommendation-name')).toHaveText(expected)
    await expect(page.getByLabel('目标知识点')).toHaveValue('optimization')
    await page.screenshot({path:`docs/screenshots/${file}.png`,fullPage:true})
    await page.getByRole('button',{name:'退出登录'}).click()
  }
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await expect(page.getByTestId('recommendation-name')).toBeVisible()
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:'docs/screenshots/mobile.png',fullPage:true})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
})

test('search really filters and renders input safely; custom practice respects settings',async ({page}) => {
  await page.goto('/')
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await page.getByRole('link',{name:'题库搜索',exact:true}).click()
  await page.getByLabel('题干关键词').fill('切线')
  await page.getByLabel('难度',{exact:true}).selectOption('2')
  await page.getByRole('button',{name:'搜索',exact:true}).click()
  await expect(page.locator('.search-result')).toHaveCount(3)
  await page.getByLabel('题干关键词').fill('<img src=x onerror=alert(1)>')
  await page.getByRole('button',{name:'搜索',exact:true}).click()
  await expect(page.locator('.search-result')).toHaveCount(0)
  await expect(page.getByRole('heading',{name:'没有找到匹配的题目'})).toBeVisible()
  await page.getByRole('link',{name:'练习中心',exact:true}).click()
  await page.getByRole('button',{name:'自定义练习'}).click()
  await page.getByLabel('知识点',{exact:true}).selectOption('tangent')
  await page.getByLabel('难度',{exact:true}).selectOption('2')
  await page.getByLabel('题量',{exact:true}).selectOption('10')
  await page.getByRole('button',{name:'开始练习',exact:true}).click()
  await expect(page.locator('.question-toolbar')).toContainText('切线方程 · 中等')
  await expect(page.locator('.question-panel .callout')).toContainText('只有 3 道')
  await expect(page.locator('.katex').first()).toBeVisible()
})

